#!/usr/bin/env node
/**
 * Terminal-Bench best-of-N benchmark runner for DSH-llm-as-a-verifier.
 *
 * This is an original TypeScript/Node runner. It reads pre-generated
 * trajectory JSON, scores candidates with this repository's verifier core,
 * and writes Pass@1 / verifier accuracy / oracle results.
 *
 * Examples:
 *   node scripts/benchmark.mjs terminal_bench_2.1 --mode bo3 --dry-run
 *   node scripts/benchmark.mjs terminal_bench_2.1 --mode bo3 --limit 3
 *   node scripts/benchmark.mjs terminal_bench_2.0 --mode terminal_v2 --limit 3
 */

import { mkdir, writeFile } from 'node:fs/promises'
import { dirname, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

import {
  BENCHMARK_PRESETS,
  estimateBenchmark,
  loadTerminalBenchmark,
  runTerminalBenchmark,
} from '../dist/lib/index.mjs'

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..')

const DATA_PATHS = {
  'terminal_bench_2.1': resolve(ROOT, 'references/llm-as-a-verifier/data/terminal_bench_2.1_trajs/mini-swe-agent_deepseek-v4-flash'),
  'terminal_bench_2.0': resolve(ROOT, 'references/llm-as-a-verifier/data/terminal_bench_2.0_trajs/capy_gpt-5.5'),
}

const DEFAULT_MODE = {
  'terminal_bench_2.1': 'bo3',
  'terminal_bench_2.0': 'terminal_v2',
}

const HELP = `Usage: node scripts/benchmark.mjs <benchmark> [options]

Benchmarks:
  terminal_bench_2.1   mini-swe-agent trajectories generated by deepseek-v4-flash
  terminal_bench_2.0   Capy trajectories generated by GPT-5.5

Options:
  --mode <name>         bo3 | bo5 | terminal_v2 (default per benchmark above)
  --data <path>         override the trajectory agent directory
  --criteria <name>     criteria name or .md path (default: terminal_bench)
  --criteria-count <n>  criteria count used only by --dry-run estimates (default 3)
  --seed <n>            tournament seed (default 0)
  --pivots <n>          override the preset pivot count
  --evaluations <n>     override the preset evaluation repeats
  --trials <n>          override how many trajectories per task are used
  --limit <n>           run only the first N tasks
  --cache <path>        score cache path (default: results/cache-<benchmark>-<mode>.json)
  --output <path>       result JSON path
  --markdown <path>     write a Markdown summary too
  --model <name>        verifier model override
  --backend <name>      deepseek | openai | auto
  --base-url <url>      verifier endpoint override
  --api-key-env <name>  credential environment name (default is backend-specific)
  --dry-run             load tasks and print cost estimate without API traffic
  --help                show this help
`

function parseArgs(argv) {
  const args = {}
  const positional = []
  for (let index = 0; index < argv.length; index += 1) {
    const token = argv[index]
    if (token === '--help') {
      args.help = true
    } else if (token === '--dry-run') {
      args.dryRun = true
    } else if (token.startsWith('--')) {
      const key = token.slice(2)
      const value = argv[index + 1]
      if (value === undefined || value.startsWith('--')) {
        console.error(`Missing value for ${token}`)
        process.exit(2)
      }
      args[key] = value
      index += 1
    } else {
      positional.push(token)
    }
  }
  return { args, positional }
}

function numberArg(args, name, fallback) {
  const value = args[name]
  if (value === undefined) return fallback
  const parsed = Number(value)
  if (!Number.isInteger(parsed) || parsed < 0) {
    console.error(`--${name} expects a non-negative integer, got ${value}`)
    process.exit(2)
  }
  return parsed
}

function presetFor(args, benchmark) {
  const base = BENCHMARK_PRESETS[args.mode ?? DEFAULT_MODE[benchmark] ?? 'bo3']
  if (base === undefined) {
    console.error(`Unknown mode "${args.mode}". Use bo3, bo5, or terminal_v2.`)
    process.exit(2)
  }
  const preset = {
    ...base,
    name: args.mode ?? base.name,
    trials: numberArg(args, 'trials', base.trials),
    pivots: numberArg(args, 'pivots', base.pivots),
    evaluations: numberArg(args, 'evaluations', base.evaluations),
  }
  return preset
}

function formatPercent(value) {
  return `${(100 * value).toFixed(2)}%`
}

function renderMarkdown(run, benchmark, sourcePath) {
  const lines = [
    `# ${benchmark} — ${run.preset.name} reproduction`,
    '',
    `- Run at: ${run.createdAt}`,
    `- Preset: trials=${run.preset.trials}, pivots=${run.preset.pivots}, evaluations=${run.preset.evaluations}, seed=${run.seed}`,
    `- Data source: \`${sourcePath}\``,
    '',
    '## Summary',
    '',
    '| Metric | Value |',
    '|---|---|',
    `| Tasks | ${run.summary.tasks} |`,
    `| Pass@1 | ${formatPercent(run.summary.passAt1)} |`,
    `| Verifier selection | ${formatPercent(run.summary.verifierAccuracy)} |`,
    `| Oracle | ${formatPercent(run.summary.oracleRate)} |`,
    `| Uplift over Pass@1 | ${formatPercent(run.summary.verifierUplift)} |`,
    `| Gap to oracle | ${formatPercent(run.summary.oracleGap)} |`,
    `| Directed comparisons | ${run.summary.nComparisons} |`,
    `| Verifier calls | ${run.summary.verifierCalls} |`,
    `| Input tokens | ${run.summary.usage.inputTokens} |`,
    `| Cached input tokens | ${run.summary.usage.cachedInputTokens} |`,
    `| Output tokens | ${run.summary.usage.outputTokens} |`,
    '',
    '> Independent reproduction with DSH-llm-as-a-verifier. Upstream reported',
    '> numbers live in the main README and are tracked separately.',
  ]
  return `${lines.join('\n')}\n`
}

async function main() {
  const { args, positional } = parseArgs(process.argv.slice(2))
  if (args.help || positional.length === 0) {
    console.log(HELP)
    process.exit(args.help ? 0 : 2)
  }

  const benchmark = positional[0]
  if (!(benchmark in DATA_PATHS)) {
    console.error(`Unknown benchmark "${benchmark}". Expected one of: ${Object.keys(DATA_PATHS).join(', ')}`)
    process.exit(2)
  }

  const preset = presetFor(args, benchmark)
  const dataPath = resolve(ROOT, args.data ?? DATA_PATHS[benchmark])
  const criteria = args.criteria ?? 'terminal_bench'
  const seed = numberArg(args, 'seed', 0)
  const limit = numberArg(args, 'limit', 0)
  const cachePath = resolve(ROOT, args.cache ?? `results/cache-${benchmark}-${preset.name}.json`)
  const outputPath = resolve(ROOT, args.output ?? `results/${benchmark}-${preset.name}.json`)
  const criteriaCount = numberArg(args, 'criteria-count', 3)

  console.log(`Benchmark: ${benchmark} (${preset.name})`)
  console.log(`Data: ${dataPath}`)

  const tasks = await loadTerminalBenchmark(dataPath, preset.trials)
  const estimate = estimateBenchmark(tasks, preset, criteriaCount)
  console.log(`Tasks: ${estimate.tasks}, candidates/task: ${preset.trials}`)
  console.log(`Estimate: ${estimate.comparisons} directed comparisons, up to ${estimate.verifierCalls} verifier calls`)

  if (args.dryRun) {
    if (limit > 0) console.log(`Limited to first ${limit} task(s) for the real run.`)
    return
  }

  const overrides = {}
  if (args.model !== undefined) overrides.model = args.model
  if (args.backend !== undefined) overrides.backend = args.backend
  if (args['base-url'] !== undefined) overrides.baseUrl = args['base-url']
  if (args['api-key-env'] !== undefined) overrides.apiKeyEnv = args['api-key-env']

  const run = await runTerminalBenchmark({
    agentDir: dataPath,
    preset,
    criteria,
    seed,
    limit: limit > 0 ? limit : undefined,
    cache: cachePath,
    overrides,
    onProgress: (done, total, taskName) => {
      console.log(`[${done}/${total}] ${taskName}`)
    },
  })

  await mkdir(dirname(outputPath), { recursive: true })
  await writeFile(outputPath, JSON.stringify(run, null, 2), 'utf8')
  console.log(`Results: ${outputPath}`)

  const markdownPath = args.markdown !== undefined ? resolve(ROOT, args.markdown) : `${outputPath.replace(/\.json$/, '')}.md`
  await mkdir(dirname(markdownPath), { recursive: true })
  await writeFile(markdownPath, renderMarkdown(run, benchmark, dataPath), 'utf8')
  console.log(`Markdown: ${markdownPath}`)

  console.log(`Pass@1 ${formatPercent(run.summary.passAt1)} -> verifier ${formatPercent(run.summary.verifierAccuracy)} (oracle ${formatPercent(run.summary.oracleRate)})`)
}

await main()
